def _md(text: str) -> str:
    return markdown.markdown(escape(text, quote=False))


def _signed(value: float) -> str:
    css = "pos" if round(value, 4) > 0 else "neg" if round(value, 4) < 0 else ""
    return f'<span class="{css}">{fmt_pct(value, signed=True)}</span>'


def _bullets(items: list[str]) -> str:
    return "<ul>" + "".join(f"<li>{escape(i)}</li>" for i in items) + "</ul>"


def _figure(analysis: FundAnalysis, key: str, number: int, caption: str) -> str:
    path = analysis.charts.get(key)
    if not path:
        return ""
    return (f'<img src="{path}"/><p class="caption">Figure {number}: {caption} '
            f'Source: uploaded data, agent calculations.</p>')


