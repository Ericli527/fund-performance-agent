def _kpi_tiles(analysis: FundAnalysis, report: FundReport) -> str:
    tiles = []
    if analysis.metrics is not None:
        m = analysis.metrics
        tiles = [
            ("FUND RETURN", fmt_pct(m.at["Total return", "Fund"]), "cumulative, full period"),
            ("BENCHMARK RETURN", fmt_pct(m.at["Total return", "Benchmark"]), escape(report.benchmark_name)),
            ("EXCESS RETURN P.A.", fmt_pct(m.at["Excess return (annualised)", "Relative"], signed=True), "fund minus benchmark"),
            ("TRACKING ERROR", fmt_pct(m.at["Tracking error", "Relative"]), f"information ratio {m.at['Information ratio', 'Relative']:.2f}"),
            ("MAX DRAWDOWN", fmt_pct(m.at["Max drawdown", "Fund"]), f"benchmark {fmt_pct(m.at['Max drawdown', 'Benchmark'])}"),
        ]
    elif analysis.attribution is not None:
        t = analysis.attribution.iloc[-1]
        tiles = [
            ("FUND RETURN", fmt_pct(t["Fund ret"]), "attribution period"),
            ("BENCHMARK RETURN", fmt_pct(t["Bmk ret"]), escape(report.benchmark_name)),
            ("ACTIVE RETURN", fmt_pct(t["Total"], signed=True), "fund minus benchmark"),
            ("ALLOCATION", fmt_pct(t["Allocation"], signed=True), "effect"),
            ("SELECTION", fmt_pct(t["Selection"], signed=True), "effect"),
        ]
    if not tiles:
        return ""
    cells = "".join(f'<td><span class="kpi-label">{label}</span><br/><span class="kpi-value">{value}</span>'
                    f'<br/><span class="kpi-sub">{sub}</span></td>' for label, value, sub in tiles)
    return f'<table class="kpi" cellspacing="4"><tr>{cells}</tr></table>'


def _periods_table(periods: pd.DataFrame) -> str:
    head = '<th class="left"></th>' + "".join(f"<th>{c}</th>" for c in periods.columns)
    rows = ""
    for name, row in periods.iterrows():
        cells = "".join(f"<td>{_signed(v) if name == 'Relative' else fmt_pct(v)}</td>" for v in row)
        css = ' class="total"' if name == "Relative" else ""
        rows += f'<tr{css}><td class="left">{name}</td>{cells}</tr>'
    return f'<table class="data" repeat="1"><tr>{head}</tr>{rows}</table>'


def _contributors_table(attribution: pd.DataFrame) -> str:
    top, bottom = top_and_bottom(attribution)
    rows = ""
    for i in range(max(len(top), len(bottom), 1)):
        t = top.iloc[i] if i < len(top) else None
        b = bottom.iloc[i] if i < len(bottom) else None
        rows += (f'<tr><td class="left">{escape(str(t.Segment)) if t is not None else "-"}</td>'
                 f'<td>{_signed(t.Total) if t is not None else ""}</td>'
                 f'<td class="left">{escape(str(b.Segment)) if b is not None else "-"}</td>'
                 f'<td>{_signed(b.Total) if b is not None else ""}</td></tr>')
    return ('<table class="data" repeat="1"><tr><th class="left">Top contributors</th><th>Effect</th>'
            f'<th class="left">Top detractors</th><th>Effect</th></tr>{rows}</table>')


def _metrics_table(metrics: pd.DataFrame) -> str:
    ratios = {"Sharpe ratio", "Information ratio", "Beta"}
    rows = ""
    for metric in metrics["Fund"].dropna().index:
        f, b = metrics.at[metric, "Fund"], metrics.at[metric, "Benchmark"]
        fmt = (lambda v: f"{v:.2f}") if metric in ratios else fmt_pct
        rows += f'<tr><td class="left">{metric}</td><td>{fmt(f)}</td><td>{fmt(b)}</td></tr>'
    for metric, v in metrics["Relative"].dropna().items():
        value = f"{v:.2f}" if metric in ratios else fmt_pct(v, signed=metric.startswith("Excess"))
        rows += f'<tr><td class="left">{metric}</td><td colspan="2">{value}</td></tr>'
    return f'<table class="data" repeat="1"><tr><th class="left">Metric</th><th>Fund</th><th>Benchmark</th></tr>{rows}</table>'


def _attribution_tables(attribution: pd.DataFrame) -> tuple[str, str]:
    t = attribution.iloc[-1]
    summary = ('<table class="data" repeat="1"><tr><th class="left">Effect</th><th>Contribution</th></tr>'
               + "".join(f'<tr><td class="left">{e}</td><td>{_signed(t[e])}</td></tr>' for e in ("Allocation", "Selection", "Interaction"))
               + f'<tr class="total"><td class="left">Active return</td><td>{_signed(t["Total"])}</td></tr></table>')
    cols = list(attribution.columns)
    head = '<th class="left">Segment</th>' + "".join(f"<th>{c}</th>" for c in cols[1:])
    rows = ""
    for _, r in attribution.iterrows():
        css = ' class="total"' if r["Segment"] == "Total" else ""
        cells = "".join(f"<td>{_signed(r[c]) if c in ('Allocation', 'Selection', 'Interaction', 'Total') else fmt_pct(r[c])}</td>" for c in cols[1:])
        rows += f'<tr{css}><td class="left">{escape(str(r["Segment"]))}</td>{cells}</tr>'
    return summary, f'<table class="data" repeat="1"><tr>{head}</tr>{rows}</table>'


def _methodology() -> str:
    periods = ", ".join(label for label, _ in HORIZONS)
    return _bullets([
        f"Returns are calculated from NAV or price levels. Periods shown: {periods} and since start, where the data covers them. Periods over one year are annualised.",
        "Volatility and tracking error are annualised standard deviations of periodic returns (fund and fund minus benchmark). The data frequency is detected from the dates.",
        "Sharpe ratio = (annualised return - risk-free rate) / volatility. Information ratio = annualised excess return / tracking error. Beta = covariance(fund, benchmark) / variance(benchmark).",
        "Attribution uses the Brinson-Fachler model: Allocation = (wp - wb) x (Rb,i - Rb); Selection = wb x (Rp,i - Rb,i); Interaction = (wp - wb) x (Rp,i - Rb,i). The effects sum to the active return.",
        f"Status rule, applied to the last 1 year and to the annualised return since start: On track if the fund's excess return is >= 0; Watch if within {abs(STATUS_WATCH_THRESHOLD):.0%} a year below; otherwise Under review. Showing both separates recent results from the long-term record. This is an illustrative rule, not a formal rating.",
    ])


GLOSSARY = [
    ("Annualised volatility", "How much returns vary around their average, as an annualised standard deviation. Higher means a bumpier ride."),
    ("Relative volatility", "Fund volatility divided by benchmark volatility. Above 1 means the fund has been more volatile than the benchmark."),
    ("Sharpe ratio", "Return above the risk-free rate per unit of volatility. Higher means better risk-adjusted performance."),
    ("Annualised alpha", "The fund's return above what its beta to the benchmark would predict."),
    ("Beta", "Sensitivity to benchmark moves. A beta of 1.10 suggests the fund rises or falls about 10% more than the benchmark."),
    ("Annualised tracking error", "The volatility of the fund's return minus the benchmark's return: how closely the fund follows the benchmark."),
    ("Information ratio", "Annualised excess return divided by tracking error: how efficiently active risk turned into extra return."),
    ("R²", "How much of the fund's movement is explained by the benchmark (0 to 1). Below about 0.5, beta and alpha are less reliable."),
    ("Risk indicator", "A 1 (lower risk) to 7 (higher risk) scale. When not supplied, it is estimated from volatility using SRRI bands."),
]


def _glossary() -> str:
    return "<ul>" + "".join(f"<li><b>{term}:</b> {text}</li>" for term, text in GLOSSARY) + "</ul>"


def build_html(report: FundReport, analysis: FundAnalysis, searches: list[str]) -> str:
    today = f"{date.today():%d %B %Y}"
    fund_name, benchmark = factsheet_names(report, analysis)
    sub = (f"Fund: {escape(fund_name)} &nbsp;|&nbsp; Benchmark: {escape(benchmark)} "
           f"&nbsp;|&nbsp; Period: {analysis.period_label} &nbsp;|&nbsp; Report date: {today}")
    status_cells = "".join(
        f'<td width="17%" style="background-color: {colour}; color: white; font-weight: bold; padding: 5px 6px; '
        f'text-align: center;"><span style="font-size: 6.5pt;">{horizon.upper()}</span><br/>{label.upper()}</td>'
        f'<td style="padding: 5px 8px; color: {GREY};">{why}</td>'
        for horizon, label, colour, why in analysis.status)
    status_html = f'<table cellspacing="0"><tr>{status_cells}</tr></table>' if status_cells else ""

    exec_parts = [
        f'<table class="banner" cellspacing="0"><tr><td><span class="banner-label">EXECUTIVE SUMMARY</span><br/><br/>'
        f'<span class="banner-title">{escape(report.title)}</span><br/><span class="banner-sub">{sub}</span></td></tr></table>',
        status_html,
        _kpi_tiles(analysis, report),
        "<h3>Key messages</h3>" + _bullets(report.key_messages),
    ]
    if analysis.periods is not None:
        exec_parts.append("<h3>Returns by period</h3>" + _periods_table(analysis.periods))
    if analysis.attribution is not None:
        exec_parts.append("<h3>Attribution snapshot</h3>" + _contributors_table(analysis.attribution))
    exec_parts.append('<h3>Recommended committee action</h3><table class="action" cellspacing="0"><tr><td>'
                      + escape(report.committee_action) + "</td></tr></table>")

    body = [build_factsheet(report, analysis), '<pdf:nexttemplate name="report" /><pdf:nextpage />',
            "\n".join(exec_parts), "<pdf:nextpage />"]
    fig = 1
    body.append("<h2>1. Performance</h2>" + _md(report.performance_commentary))
    if analysis.periods is not None:
        body.append(_figure(analysis, "growth", fig, f"Growth of 100, {analysis.period_label}."))
        fig += 1
    body.append("<h2>2. Risk</h2>" + _md(report.risk_commentary))
    if analysis.metrics is not None:
        body.append(_figure(analysis, "drawdown", fig, "Drawdown from previous peak."))
        fig += 1
        body.append("<h3>Risk and return metrics</h3>" + _metrics_table(analysis.metrics))
    body.append("<h2>3. Attribution</h2>" + _md(report.attribution_commentary))
    if analysis.attribution is not None:
        summary, full = _attribution_tables(analysis.attribution)
        body.append("<h3>Summary of effects</h3>" + summary)
        body.append(_figure(analysis, "attribution", fig, "Attribution effects by segment (Brinson-Fachler)."))
        body.append('<h3>Attribution by segment</h3><p class="small">Bmk = benchmark, wt = weight, ret = return. '
                    'Effects are contributions to active return.</p>' + full)
    body.append("<h2>4. Market context</h2>" + _md(report.market_context))
    body.append("<h2>5. Outlook and risks to monitor</h2>" + _bullets(report.outlook_and_risks))

    files = list(dict.fromkeys([n.split(":")[0] for n in analysis.parsed.notes if "read as" in n]
                               + [n for n, _ in analysis.parsed.documents]))
    body.append("<h2>Appendix: Methodology, glossary and sources</h2><h3>Methodology</h3>" + _methodology())
    body.append("<h3>Glossary</h3>" + _glossary())
    ai_sources = sorted({v for v in analysis.parsed.sources.values() if "AI-extracted" in v})
    body.append("<h3>Data sources</h3>" + _bullets([f"Uploaded: {f}" for f in files]
                                                   + ([analysis.parsed.sources["nav"]] if "EODHD" in analysis.parsed.sources.get("nav", "") else [])
                                                   + [f"Some factsheet data was {s}" for s in ai_sources] or ["No files uploaded"])
                + "<h3>Web searches</h3>" + _bullets(searches or ["None"]))
    body.append(f'<p class="small">{DISCLAIMER}</p>')

    footer = (f'<div id="footer_content">{escape(fund_name)} &nbsp;|&nbsp; Factsheet and performance review, {today} '
              f'&nbsp;|&nbsp; For committee use &nbsp;|&nbsp; Page <pdf:pagenumber> of <pdf:pagecount></div>')
    return f"<html><head><style>{CSS}</style></head><body>{footer}{''.join(body)}</body></html>"


# ---------- Markdown (app and email) ----------

def build_markdown(report: FundReport, analysis: FundAnalysis, searches: list[str]) -> str:
    from calculator import period_returns_to_markdown, metrics_to_markdown, attribution_to_markdown
    parts = [f"# {report.title}",
             f"*{report.fund_name} vs {report.benchmark_name} · {analysis.period_label} · {date.today():%d %B %Y}*",
             "## Executive summary"]
    for horizon, label, _, why in analysis.status:
        parts.append(f"**Status ({horizon}): {label}** — {why}")
    parts.append("\n".join(f"- {m}" for m in report.key_messages))
    if analysis.periods is not None:
        parts.append("**Returns by period**\n\n" + period_returns_to_markdown(analysis.periods))
    if analysis.attribution is not None:
        top, bottom = top_and_bottom(analysis.attribution)
        parts.append("**Top contributors:** " + ", ".join(f"{r.Segment} ({fmt_pct(r.Total, True)})" for r in top.itertuples())
                     + "  \n**Top detractors:** " + ", ".join(f"{r.Segment} ({fmt_pct(r.Total, True)})" for r in bottom.itertuples()))
    parts.append(f"> **Committee action:** {report.committee_action}")
    parts.append(f"## 1. Performance\n\n{report.performance_commentary}")
    parts.append(f"## 2. Risk\n\n{report.risk_commentary}")
    if analysis.metrics is not None:
        parts.append(metrics_to_markdown(analysis.metrics))
    parts.append(f"## 3. Attribution\n\n{report.attribution_commentary}")
    if analysis.attribution is not None:
        parts.append(attribution_to_markdown(analysis.attribution))
    parts.append(f"## 4. Market context\n\n{report.market_context}")
    parts.append("## 5. Outlook and risks to monitor\n\n" + "\n".join(f"- {r}" for r in report.outlook_and_risks))
    parts.append("## Sources\n\n" + "\n".join(f"- {s}" for s in searches))
    parts.append(f"*{DISCLAIMER}*")
    return "\n\n".join(parts)
