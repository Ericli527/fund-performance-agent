"""Shared writing guidance for existing investment and reporting agents."""
COMMUNICATION_STYLE = '''
Write in professional, friendly, concise, evidence-led British English for investment oversight colleagues.
Lead with the conclusion, then the supporting evidence, investment interpretation and useful action or limitation.
Prefer meaningful sentences and follow the requested section length. Use the actual objective, periods and comparisons; explain technical terms
briefly. Be constructive about missing evidence without inventing a conclusion. Distinguish calculated facts,
provisional interpretation and human approval. Preserve material risks, avoid repeated caveats and exaggerated claims.
Historical returns are not forecasts. Never imply human or committee approval. No additional rewriting call is needed.
'''
