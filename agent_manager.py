DISCLAIMER = ("This report was generated by an AI agent for demonstration purposes. "
              "It is not investment advice. Figures are calculated from the uploaded data.")


class FundAnalysis:
    """ Numbers and charts calculated in Python, so the LLM never does arithmetic """

    def __init__(self, parsed: ParsedFiles, out_dir: Path):
        self.parsed = parsed
        self.sections: list[str] = []
        self.charts: list[str] = []
        if parsed.nav is not None and len(parsed.nav) >= 3:
            nav = parsed.nav
            period = f"{nav['date'].iloc[0]:%d %b %Y} to {nav['date'].iloc[-1]:%d %b %Y}"
            self.sections.append(f"### Performance ({period})\n\n{metrics_to_markdown(performance_metrics(nav))}")
            self.charts.append(growth_chart(nav, str(out_dir / "growth.png")))
        if parsed.attribution is not None:
            attribution = brinson_attribution(parsed.attribution)
            self.sections.append("### Attribution (Brinson-Fachler)\n\n" + attribution_to_markdown(attribution))
            self.charts.append(attribution_chart(attribution, str(out_dir / "attribution.png")))

    def tables_markdown(self) -> str:
        return "\n\n".join(self.sections) or "No NAV or attribution data was uploaded."

    def documents_text(self) -> str:
        return "\n\n".join(f"--- {name} ---\n{text}" for name, text in self.parsed.documents) or "None"


class AgentManager:

    async def run(self, query: str, files: list[str] | None):
        """ Run the fund report workflow, yielding (report, summary, pdf, charts) updates """
        status: list[str] = []

        def update(message: str):
            status.append(message)
            return "\n".join(f"- {s}" for s in status), "", None, []

        trace_id = gen_trace_id()
        with trace("Fund report trace", trace_id=trace_id):
            yield update(f"Starting. [View trace](https://platform.openai.com/traces/trace?trace_id={trace_id})")
            out_dir = Path(tempfile.mkdtemp(prefix="fund_report_"))

            analysis = FundAnalysis(parse_files(files), out_dir)
            for note in analysis.parsed.notes:
                yield update(note)
            yield update("Calculations done, planning searches...")

            plan = await self.plan_searches(query, analysis)
            yield update(f"Running {len(plan.searches)} searches...")
            search_results = await self.perform_searches(plan)
            yield update(f"{len(search_results)} of {len(plan.searches)} searches succeeded, writing report...")

            report = await self.write_report(query, analysis, search_results)
            report_md = self.assemble_report(report, analysis, plan, with_charts=False)
            pdf_path = build_pdf(self.assemble_report(report, analysis, plan, with_charts=True),
                                 str(out_dir / "fund_report.pdf"))
            yield update("PDF created, sending email and push notification...")

            notify_result = await self.notify(report, report_md, pdf_path)
            yield update(notify_result)
            yield report_md, report.short_summary, pdf_path, analysis.charts

    async def plan_searches(self, query: str, analysis: FundAnalysis) -> WebSearchPlan:
        """ Plan the searches, with a hard limit in code as well as in the prompt """
        input_message = f"Request: {query}\n\nCalculated results:\n{analysis.tables_markdown()}"
        result = await Runner.run(planner_agent, input_message)
        plan = result.final_output
        plan.searches = plan.searches[:HOW_MANY_SEARCHES]
        return plan

    async def perform_searches(self, plan: WebSearchPlan) -> list[str]:
        """ Run the searches in parallel, skipping any that fail """
        results = await asyncio.gather(*(self.search(item) for item in plan.searches), return_exceptions=True)
        return [r for r in results if isinstance(r, str)]

    async def search(self, item: WebSearchItem) -> str:
        input_message = f"Search term: {item.query}\nReason for searching: {item.reason}"
        result = await Runner.run(search_agent, input_message)
        return result.final_output

    async def write_report(self, query: str, analysis: FundAnalysis, search_results: list[str]) -> FundReport:
        input_message = (
            f"Request: {query}\n\n"
            f"Calculated tables:\n{analysis.tables_markdown()}\n\n"
            f"Uploaded documents:\n{analysis.documents_text()}\n\n"
            f"Web search summaries:\n{search_results}"
        )
        result = await Runner.run(writer_agent, input_message)
        return result.final_output

    def assemble_report(self, report: FundReport, analysis: FundAnalysis, plan: WebSearchPlan, with_charts: bool) -> str:
        """ Combine the Python-calculated tables with the LLM commentary """
        parts = [f"# {report.title}", f"*Generated {date.today():%d %B %Y}*",
                 f"## Summary\n\n{report.short_summary}", "## Key figures", analysis.tables_markdown()]
        if with_charts:
            parts += [f"![chart]({chart})" for chart in analysis.charts]
        parts.append(report.commentary)
        searches = "\n".join(f"- {s.query}" for s in plan.searches)
        parts.append(f"## Sources\n\n**Web searches:**\n\n{searches}")
        parts.append(f'<p class="disclaimer">{DISCLAIMER}</p>' if with_charts else f"*{DISCLAIMER}*")
        return "\n\n".join(parts)

    async def notify(self, report: FundReport, report_md: str, pdf_path: str) -> str:
        input_message = f"Short summary:\n{report.short_summary}\n\nFull report:\n{report_md}"
        result = await Runner.run(notify_agent, input_message, context=NotifyContext(pdf_path=pdf_path))
        return result.final_output
